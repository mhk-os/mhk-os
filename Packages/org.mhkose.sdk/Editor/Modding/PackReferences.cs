using System;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using MHK.Modding;
using UnityEditor;
using UnityEditorInternal;
using UnityEngine;
using Object = UnityEngine.Object;

namespace MHK.Editor.Modding
{
    /// <summary>
    /// Reference packages in the SDK (<see cref="FolderName"/>, never imported by the game): one stub per definition of a
    /// mod with the real asset's GUID and fileID, so other mod projects can refer to its content. org.mhkose.sdk.corerefs
    /// holds the game's core, org.mhkose.sdk.refs.&lt;pack id&gt; each base mod (exported from the mod's own project).
    /// </summary>
    public static class PackReferences
    {
        /// <summary>Folder of the reference packages inside the SDK.</summary>
        public const string FolderName = "CoreRefs~";
        /// <summary>Package name prefix of a mod's reference package.</summary>
        public const string ModPackagePrefix = "org.mhkose.sdk.refs.";
        /// <summary>Index of a mod's reference package (<see cref="CoreIndex"/> format), merged by <see cref="CoreIndex.Load"/>.</summary>
        public const string IndexFile = "index.json";
        const string MenuPath = "MHK/Modding/Export References of Selected Packs";
        const long MainObjectFileId = 11400000;

        [Serializable]
        class PackageManifest
        {
            public string name;
        }

        /// <summary>Folder of the SDK's reference packages on disk.</summary>
        public static string Root => Path.Combine(SdkPaths.ResolvedRoot, FolderName);

        /// <summary>Package name of the reference package of the mod <paramref name="packId"/>.</summary>
        public static string PackageName(string packId) => ModPackagePrefix + packId;

        [MenuItem(MenuPath, priority = 30)]
        static void ExportMenu()
        {
            foreach (var pack in Selection.GetFiltered<ContentPack>(SelectionMode.Assets)) Export(pack);
        }

        [MenuItem(MenuPath, true)]
        static bool ExportValidate() => Selection.GetFiltered<ContentPack>(SelectionMode.Assets).Length > 0;

        /// <summary>
        /// Writes the reference package of the mod <paramref name="root"/> (its definitions and those of the packs it
        /// includes) into the SDK, replacing an earlier export. Returns false when a definition got no stub.
        /// </summary>
        public static bool Export(ContentPack root)
        {
            var name = PackageName(root.packId);
            var folder = Path.Combine(Root, name);
            if (!PrepareFolder(folder, name)) return false;
            var index = new CoreIndex();
            var count = 0;
            var written = 0;
            foreach (var pack in root.SelfAndIncluded())
            {
                index.packs.Add(new CoreIndex.Pack { packId = pack.packId, root = root.packId });
                foreach (var def in pack.content.Where(d => d != null))
                {
                    count++;
                    if (WriteStub(folder, pack, def)) written++;
                    index.Add(pack, def);
                }
            }
            WritePackage(folder, name, root.title + " References",
                $"Stand-ins for the definitions of the mod {root.title} with the GUIDs of its assets, so other mods can refer to its content. " +
                "The game resolves them by id when the mods load. Generated by the mod's project (MHK > Modding > Export References of Selected Packs).");
            WriteText(folder, Path.Combine(folder, IndexFile), JsonUtility.ToJson(index, true) + "\n", "TextScriptImporter");
            Debug.Log($"[Mods] References of '{root.packId}': {written} stubs of {count} definitions in {folder}.");
            return written == count;
        }

        /// <summary>Empties <paramref name="folder"/> when it holds the package <paramref name="name"/>, refuses other non-empty folders and folders this project imports.</summary>
        public static bool PrepareFolder(string folder, string name)
        {
            folder = Path.GetFullPath(folder);
            var project = Path.GetFullPath(".") + Path.DirectorySeparatorChar;
            var imported = folder.StartsWith(project + "Assets") || folder.StartsWith(project + "Packages");
            if (imported && !folder.Split(Path.DirectorySeparatorChar).Any(s => s.EndsWith("~")))
            {
                Debug.LogError($"[SDK] {folder} is imported by this project: the stubs would clash with the real definitions. Pick a folder outside " +
                               "Assets and Packages or inside a folder whose name ends with '~'.");
                return false;
            }
            var manifest = Path.Combine(folder, "package.json");
            if (Directory.Exists(folder) && Directory.EnumerateFileSystemEntries(folder).Any())
            {
                if (!File.Exists(manifest) || JsonUtility.FromJson<PackageManifest>(File.ReadAllText(manifest)).name != name)
                {
                    Debug.LogError($"[SDK] {folder} is not empty and holds no {name} package: nothing written.");
                    return false;
                }
                Directory.Delete(folder, true);
            }
            Directory.CreateDirectory(folder);
            return true;
        }

        /// <summary>Writes the stub of <paramref name="def"/> into the subfolder of its pack, with a copy of the real asset's meta.</summary>
        public static bool WriteStub(string folder, ContentPack pack, ContentDefinition def)
        {
            if (!AssetDatabase.TryGetGUIDAndLocalFileIdentifier(def, out var guid, out long fileId) || fileId != MainObjectFileId)
            {
                Debug.LogError($"[SDK] '{def.Id}' is not the main object of its asset file: no stub with the same GUID and fileID possible.", def);
                return false;
            }
            var name = AssetPaths.SafeFileName(def.Id);
            var dir = Path.Combine(folder, pack.packId);
            Directory.CreateDirectory(dir);
            var path = Path.Combine(dir, name + ".asset");
            var stub = (ContentDefinition)ScriptableObject.CreateInstance(def.GetType());
            stub.name = name;
            using (var so = new SerializedObject(stub))
            {
                so.FindProperty("id").stringValue = def.Id;
                so.FindProperty("displayName").stringValue = def.DisplayName;
                so.ApplyModifiedPropertiesWithoutUndo();
            }
            InternalEditorUtility.SaveToSerializedFileAndForget(new Object[] { stub }, path, true);
            Object.DestroyImmediate(stub);
            // The serializer numbers the object 1, references to the real definition use the main object id.
            var yaml = File.ReadAllText(path);
            var header = yaml.IndexOf(" &1\n", StringComparison.Ordinal);
            if (header < 0) throw new IOException($"Unexpected stub layout in {path}");
            File.WriteAllText(path, yaml.Substring(0, header) + $" &{MainObjectFileId}\n" + yaml.Substring(header + 4));
            File.Copy(Path.GetFullPath(AssetDatabase.GUIDToAssetPath(guid)) + ".meta", path + ".meta", true);
            return true;
        }

        /// <summary>Writes package.json and the metas of the pack subfolders of the reference package in <paramref name="folder"/>.</summary>
        public static void WritePackage(string folder, string name, string displayName, string description)
        {
            foreach (var dir in Directory.GetDirectories(folder))
                File.WriteAllText(dir + ".meta", Meta(folder, dir, "folderAsset: yes\nDefaultImporter"));
            var json = "{\n" +
                       $"  \"name\": \"{name}\",\n" +
                       $"  \"version\": \"{SdkPaths.PackageVersion}\",\n" +
                       $"  \"displayName\": \"{displayName}\",\n" +
                       $"  \"description\": \"{description}\",\n" +
                       "  \"unity\": \"6000.6\"\n" +
                       "}\n";
            WriteText(folder, Path.Combine(folder, "package.json"), json, "PackageManifestImporter");
        }

        static void WriteText(string folder, string path, string text, string importer)
        {
            File.WriteAllText(path, text);
            File.WriteAllText(path + ".meta", Meta(folder, path, importer));
        }

        // Metas of generated folders and files get a GUID derived from the package and the path, so every export writes the same one.
        static string Meta(string root, string path, string importer)
        {
            var key = Path.GetFileName(root) + "/" + Path.GetRelativePath(root, path).Replace('\\', '/');
            using var md5 = MD5.Create();
            var guid = string.Concat(md5.ComputeHash(Encoding.UTF8.GetBytes(key)).Select(b => b.ToString("x2")));
            return $"fileFormatVersion: 2\nguid: {guid}\n{importer}:\n  externalObjects: {{}}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n";
        }
    }
}
